import type { ExploreApp, ExploreAppTexts, ExploreLevel, LevelTexts } from './model.ts'

// Content is data (`content/explore/`, SPEC § 6.2), written by `authoring/generate.ts`.
function level(app: string, data: unknown, fr: unknown, en: unknown): ExploreLevel {
  return {
    ...(data as Omit<ExploreLevel, 'app' | 'texts'>),
    app,
    texts: { fr: fr as LevelTexts, en: en as LevelTexts },
  }
}

function app(data: unknown, fr: unknown, en: unknown, levels: ExploreLevel[]): ExploreApp {
  return {
    ...(data as Omit<ExploreApp, 'texts' | 'levels'>),
    levels,
    texts: { fr: fr as ExploreAppTexts, en: en as ExploreAppTexts },
  }
}

